#!/usr/bin/env python3
"""Stage high-confidence pre-1999 postseason official stat repairs.

This generates a stage directory compatible with
apply_combined_identity_promotion_20260509.py:

  - combined_promotion_rows_full.parquet
  - delete_player_weeks.csv
  - metric_recompute_scope.csv
  - rank_recompute_scope.csv
  - manifest.json

The repair set is generated by applying the guarded PBP postseason official
repair helper to the cached Fly weekly slice, then fetching the corresponding
full live rows from Fly and recalculating points locally.
"""

